def _reexport(modname, names):
    """Bind every name the submodule actually has. Names absent here
    (optional-dependency bindings, deleted except-aliases) are absent
    in MCX81 too under the same environment: identical surface."""
    mod = _importlib.import_module('node.' + modname)
    g = globals()
    for _nm in names:
        try:
            g[_nm] = getattr(mod, _nm)
        except AttributeError:
            pass

